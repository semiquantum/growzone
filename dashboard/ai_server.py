@app.get("/api/razorpay/config")
def razorpay_config():
    _, key_id, error = get_razorpay_client()
    return jsonify({"enabled": not bool(error), "key_id": key_id})


@app.post("/api/razorpay/order")
def razorpay_order():
    client, key_id, error = get_razorpay_client()
    if error:
        return jsonify({"error": error}), 500

    payload = request.get_json(silent=True) or {}
    plan = str(payload.get("plan", "")).strip().lower()
    cycle = str(payload.get("billing_cycle", "monthly")).strip().lower()

    if plan not in PRICING_TABLE:
        return jsonify({"error": "Invalid plan selected."}), 400
    if cycle not in {"monthly", "yearly"}:
        return jsonify({"error": "Invalid billing cycle selected."}), 400

    amount = int(PRICING_TABLE[plan][cycle])
    if amount <= 0:
        return jsonify({"error": "Selected plan does not require payment."}), 400

    receipt = f"growzone-{plan}-{cycle}-{int(time())}"
    try:
        order = client.order.create(
            {
                "amount": amount,
                "currency": DEFAULT_CURRENCY,
                "receipt": receipt,
                "notes": {"plan": plan, "billing_cycle": cycle},
            }
        )
    except Exception as exc:  # noqa: BLE001
        return jsonify({"error": f"Unable to create Razorpay order: {exc}"}), 502

    return jsonify(
        {
            "key_id": key_id,
            "order": order,
            "plan": plan,
            "billing_cycle": cycle,
            "amount": amount,
            "currency": DEFAULT_CURRENCY,
        }
    )


@app.post("/api/razorpay/verify")
def razorpay_verify():
    client, _, error = get_razorpay_client()
    if error:
        return jsonify({"error": error}), 500

    payload = request.get_json(silent=True) or {}
    order_id = str(payload.get("razorpay_order_id", "")).strip()
    payment_id = str(payload.get("razorpay_payment_id", "")).strip()
    signature = str(payload.get("razorpay_signature", "")).strip()

    if not order_id or not payment_id or not signature:
        return jsonify({"error": "Missing payment verification fields."}), 400

    try:
        client.utility.verify_payment_signature(
            {
                "razorpay_order_id": order_id,
                "razorpay_payment_id": payment_id,
                "razorpay_signature": signature,
            }
        )
    except Exception as exc:  # noqa: BLE001
        return jsonify({"verified": False, "error": f"Signature verification failed: {exc}"}), 400

    return jsonify({"verified": True, "message": "Payment verified successfully."})


@app.get("/")
def index():
    return send_from_directory(ROOT_DIR, "index.html")


@app.get("/<path:filename>")
def static_files(filename: str):
    if "/" in filename or "\\" in filename or filename.startswith("."):
        abort(404)

    file_path = ROOT_DIR / filename
    if not file_path.is_file():
        abort(404)

    return send_from_directory(ROOT_DIR, filename)


if __name__ == "__main__":
    port = int(os.getenv("PORT", "5000"))
    app.run(host="0.0.0.0", port=port, debug=True)
